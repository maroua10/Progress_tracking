"""Prepare small, licensed Unicode fonts ahead of deployment (fonttools required).
No font subsetting or shared stream queues run in the Worker request path.
The full fonts remain available for characters outside the compact coverage.
"""
from pathlib import Path
import base64
from fontTools import subset
root=Path(__file__).resolve().parents[1]
assets=root/'lib/assets/report-fonts'
ranges='U+0000-04FF,U+1D00-23FF,U+25A0-25FF'
for name in ['DejaVuSans','DejaVuSans-Bold']:
    subset.main([str(assets/(name+'.ttf')),'--output-file='+str(assets/(name+'-compact.ttf')),'--unicodes='+ranges,'--layout-features=*','--no-hinting'])
entries=[('reportRegularFont','DejaVuSans.ttf'),('reportBoldFont','DejaVuSans-Bold.ttf'),('reportCompactRegularFont','DejaVuSans-compact.ttf'),('reportCompactBoldFont','DejaVuSans-Bold-compact.ttf')]
lines=['// Generated by scripts/prepare-report-fonts.py. License: lib/assets/report-fonts/LICENSE.txt.']
for key,name in entries:lines.append('export const '+key+'="'+base64.b64encode((assets/name).read_bytes()).decode()+'";')
(root/'lib/report-fonts.ts').write_text('\n'.join(lines)+'\n')
print('Font assets prepared:',{name:(assets/name).stat().st_size for _,name in entries})
